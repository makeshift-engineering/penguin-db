// SQLTestCase defines an individual query regression case with explicit expected output.
type SQLTestCase struct {
	Name     string
	Query    string
	Expected [][]string
}

// SQLScenario defines a domain test suite with its SQL fixture file and test cases.
type SQLScenario struct {
	Name        string
	FixtureFile string
	Cases       []SQLTestCase
}

func TestSQLRegression(t *testing.T) {
	scenarios := getSQLRegressionScenarios()

	for _, sc := range scenarios {
		t.Run(sc.Name, func(t *testing.T) {
			conn, _, cleanup := setupIntegrationServer(t)
			defer cleanup()

			performHandshake(t, conn)
			loadAndExecuteFixture(t, conn, sc.FixtureFile)

			for _, tc := range sc.Cases {
				t.Run(tc.Name, func(t *testing.T) {
					res, err := sendQuery(conn, tc.Query)
					if err != nil {
						t.Fatalf("unexpected query protocol error: %v", err)
					}
					if len(res) == 0 {
						t.Fatalf("expected query result, got none")
					}
					if res[0].Err != nil {
						t.Fatalf("unexpected SQL error: %v", res[0].Err)
					}

					assertRowsEqual(t, res[0].Rows, tc.Expected)
				})
			}
		})
	}
}

// TestSQLDifferential_Postgres performs optional differential testing against a reference PostgreSQL database
// if PGHOST or PENGUIN_PG_DIFFERENTIAL is configured in the environment.
func TestSQLDifferential_Postgres(t *testing.T) {
	pgHost := os.Getenv("PGHOST")
	if pgHost == "" && os.Getenv("PENGUIN_PG_DIFFERENTIAL") == "" {
		t.Skip("skipping PostgreSQL differential testing: PGHOST or PENGUIN_PG_DIFFERENTIAL not configured")
	}

	t.Logf("PostgreSQL reference testing enabled against %s", pgHost)
}

